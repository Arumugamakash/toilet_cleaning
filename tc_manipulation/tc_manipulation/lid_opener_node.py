class LidOpenerNode(Node):
    """
    Autonomous lid-opening node.

    Drives the robot base to the toilet, plans an OMPL path to the lid
    grasp pose, positions the gripper, then executes the arc-waypoint
    Cartesian trajectory to lift the lid.
    """

    def __init__(self):
        super().__init__('lid_opener_node')

        # ── Frame parameters ──────────────────────────────────────────────────
        self.declare_parameter('planning_frame', 'world')
        self.declare_parameter('toilet_frame', 'toilet')
        self.declare_parameter('base_frame', 'base_link')
        self.declare_parameter('end_effector_frame', 'gripper_base_link')
        self.declare_parameter('move_group', 'xarm7_arm')

        # ── Base navigation parameters ─────────────────────────────────────────
        # Target pose is expressed in the toilet frame so it stays correct
        # regardless of where the toilet is placed in the world.
        self.declare_parameter('base_target_x', 0.90)    # metres, in front of toilet
        self.declare_parameter('base_target_y', 0.0)
        self.declare_parameter('base_target_yaw', 3.14159)  # pi → robot faces toilet
        self.declare_parameter('min_safe_base_x', 0.90)  # minimum allowed approach
        self.declare_parameter('max_base_speed', 0.06)   # m/s
        self.declare_parameter('max_base_turn_speed', 0.20)  # rad/s
        self.declare_parameter('nav_xy_tol', 0.04)       # 4 cm position tolerance
        self.declare_parameter('nav_yaw_tol', 0.04)      # ~2.3° heading tolerance
        
        # ── Grasp geometry (in toilet frame) ──────────────────────────────────
        self.declare_parameter('gap_x', 0.40)      # metres in front of toilet (toilet X-axis)
        self.declare_parameter('gap_y', 0.0)
        self.declare_parameter('gap_z', 0.395)     # height of the lid edge
        
        # Offset from gripper_base_link to gripper_finger
        # (gripper_finger = gripper_base_link + offset)
        self.declare_parameter('finger_offset_x', 0.064)
        self.declare_parameter('finger_offset_y', 0.033)
        self.declare_parameter('finger_offset_z', -0.020)
        
        # Orientation of the grasp relative to the toilet frame
        self.declare_parameter('gap_roll', 0.0)
        self.declare_parameter('gap_pitch', 1.5708)   # blade horizontal (X points down)
        self.declare_parameter('gap_yaw', 3.14159)
        self.declare_parameter('gap_approach_offset', 0.20)  # pull-back (unused in OMPL flow)

        # ── Gripper physical offsets (retained for reference; not used in planning) ──
        # Planning now targets gripper_base_link directly, so no chain offsets needed.
        self.declare_parameter('gripper_tip_offset', 0.02)
        self.declare_parameter('gripper_blade_offset_x', -0.050)
        self.declare_parameter('gripper_blade_offset_y', 0.006)
        self.declare_parameter('gripper_blade_offset_z', 0.02)
        self.declare_parameter('gripper_yaw_offset', 3.14159)

        # ── Lid arc parameters ─────────────────────────────────────────────────
        self.declare_parameter('theta_start', 0.0001)
        self.declare_parameter('theta_end', 1.63)   
        self.declare_parameter('num_waypoints', 20)

        # Hinge transform relative to toilet (from URDF)
        self.hinge_origin_xyz = [-0.07218, 0.0, 0.42234]
        self.hinge_origin_rpy = [1.5708, 0.0, 0.0]

        # ── Speed / timing parameters ──────────────────────────────────────────
        # Larger value = slower trajectory (time is stretched by this factor).
        self.declare_parameter('arm_speed_scale', 12.0)
        self.declare_parameter('speed_scale', 5.0)        # for the arc opening move

        # Blade tilt fraction (prevents wrist joint limits during the arc)
        self.declare_parameter('tilt_fraction', 0.4)

        # ── State machine ──────────────────────────────────────────────────────
        self.state = 'NAVIGATING_AND_CHECKING_REACH'
        self.is_checking_reachability = False
        self.current_goal_handle = None

        # ── TF2 ───────────────────────────────────────────────────────────────
        self.tf_buffer = tf2_ros.Buffer()
        self.tf_listener = tf2_ros.TransformListener(self.tf_buffer, self)

        # ── ROS publishers / clients ───────────────────────────────────────────
        self.cmd_vel_pub = self.create_publisher(Twist, 'cmd_vel', 10)
        self.waypoint_pub = self.create_publisher(PoseArray, 'lid_arc_waypoints', 10)

        self.compute_path_client = self.create_client(
            GetCartesianPath, 'compute_cartesian_path'
        )
        self.execute_client = ActionClient(self, ExecuteTrajectory, 'execute_trajectory')
        self.move_group_client = ActionClient(self, MoveGroup, 'move_action')

        self.get_logger().info(
            "Lid Opener Node initialised. Starting state machine (NAVIGATING)..."
        )
        # 0.1 s tick — fast enough for smooth P-controller base navigation
        self.timer = self.create_timer(0.1, self.state_machine_tick)

    # ─────────────────────────────────────────────────────────────────────────
    # TF helper
    # ─────────────────────────────────────────────────────────────────────────

    def get_transform_matrix(self, frame_id, child_frame_id):
        """Return the 4×4 homogeneous transform from frame_id to child_frame_id,
        or None if the lookup fails."""
        try:
            t = self.tf_buffer.lookup_transform(
                frame_id, child_frame_id, rclpy.time.Time()
            )
            q = [
                t.transform.rotation.x, t.transform.rotation.y,
                t.transform.rotation.z, t.transform.rotation.w,
            ]
            tr = [
                t.transform.translation.x,
                t.transform.translation.y,
                t.transform.translation.z,
            ]
            return np.dot(translation_matrix(tr), quaternion_matrix(q))
        except Exception as e:
            self.get_logger().warn(f"TF lookup [{frame_id}→{child_frame_id}] failed: {e}")
            return None

    # ─────────────────────────────────────────────────────────────────────────
    # State machine tick
    # ─────────────────────────────────────────────────────────────────────────

    def state_machine_tick(self):
        if self.state == 'NAVIGATING_AND_CHECKING_REACH':
            self.navigate_and_check()
        elif self.state == 'FINAL_PLANNING':
            # Keep base stopped firmly just in case
            self.cmd_vel_pub.publish(Twist())
            self.perform_final_plan()
        elif self.state == 'EXECUTING_ARM':
            # Arm execution is asynchronous, just wait here
            pass
        elif self.state == 'GRIPPING':
            # Gripper positioning is handled in handle_gripping().
            pass
        elif self.state == 'OPENING_LID':
            # Arc execution is asynchronous; driven by callbacks.
            pass
        elif self.state == 'DONE':
            self.get_logger().info("Lid opening completed or aborted. Node idle.", once=True)
            self.timer.cancel()

    # ─────────────────────────────────────────────────────────────────────────
    # NAVIGATING_AND_CHECKING_REACH
    # ─────────────────────────────────────────────────────────────────────────

    def navigate_and_check(self):
        """P-controller that drives the mobile base to the pre-grasp position
        in front of the toilet, while simultaneously checking arm reachability."""
        planning_frame = self.get_parameter('planning_frame').value
        toilet_frame   = self.get_parameter('toilet_frame').value
        base_frame     = self.get_parameter('base_frame').value

        T_world_toilet = self.get_transform_matrix(planning_frame, toilet_frame)
        T_world_base   = self.get_transform_matrix(planning_frame, base_frame)

        if T_world_toilet is None or T_world_base is None:
            return  # wait until TF is available

        tx   = self.get_parameter('base_target_x').value
        ty   = self.get_parameter('base_target_y').value
        tyaw = self.get_parameter('base_target_yaw').value
        min_safe_x = self.get_parameter('min_safe_base_x').value

        # Clamp the approach to the safety boundary
        tx = max(tx, min_safe_x)

        # Build target pose in world frame (via toilet frame)
        q_target = euler_to_quaternion(0.0, 0.0, tyaw)
        T_toilet_target = np.dot(translation_matrix([tx, ty, 0.0]),
                                 quaternion_matrix(q_target))
        T_world_target = np.dot(T_world_toilet, T_toilet_target)

        # Express error in the robot base frame
        T_base_target = np.dot(np.linalg.inv(T_world_base), T_world_target)
        err_x   = T_base_target[0, 3]
        err_y   = T_base_target[1, 3]
        err_yaw = math.atan2(T_base_target[1, 0], T_base_target[0, 0])
        dist    = math.sqrt(err_x**2 + err_y**2)

        # Safety: check current distance in toilet frame
        T_toilet_base   = np.dot(np.linalg.inv(T_world_toilet), T_world_base)
        curr_base_x = T_toilet_base[0, 3]

        if curr_base_x < min_safe_x - 0.02:
            self.cmd_vel_pub.publish(Twist())
            self.get_logger().error(
                f"SAFETY STOP! Base too close to toilet: "
                f"{curr_base_x:.3f} m < {min_safe_x:.3f} m. Aborting navigation."
            )
            self.state = 'DONE'
            return

        tol_xy  = self.get_parameter('nav_xy_tol').value
        tol_yaw = self.get_parameter('nav_yaw_tol').value
        max_spd = self.get_parameter('max_base_speed').value
        max_trn = self.get_parameter('max_base_turn_speed').value

        # Only publish movement if we haven't reached the absolute max target
        if dist > tol_xy or abs(err_yaw) > tol_yaw:
            msg = Twist()
            msg.linear.x  = max(-max_spd, min(max_spd, err_x * 0.4))
            msg.angular.z = max(-max_trn, min(max_trn, err_yaw * 0.8))
            self.cmd_vel_pub.publish(msg)
        else:
            self.cmd_vel_pub.publish(Twist())
            if not self.is_checking_reachability:
                self.get_logger().error(
                    "Reached navigation target but arm is still not reachable. Aborting."
                )
                self.state = 'DONE'
            return

        # Continuous reachability checking while moving
        if not self.is_checking_reachability:
            grasp_pose = self.compute_grasp_pose()
            if grasp_pose is not None:
                self.is_checking_reachability = True
                speed = self.get_parameter('arm_speed_scale').value
                self._plan_freespace_move(grasp_pose, speed, callback_type='reachability')

    def perform_final_plan(self):
        """Perform one final MoveIt plan now that the base is completely stationary."""
        if self.is_checking_reachability:
            return  # waiting on the previous request or a currently running final plan
        
        self.is_checking_reachability = True
        grasp_pose = self.compute_grasp_pose()
        if grasp_pose is not None:
            self.get_logger().info("Base stopped. Requesting FINAL planning from stationary base...")
            speed = self.get_parameter('arm_speed_scale').value
            self._plan_freespace_move(grasp_pose, speed, callback_type='final')
        else:
            self.is_checking_reachability = False

    # ─────────────────────────────────────────────────────────────────────────
    # Grasp pose computation
    # ─────────────────────────────────────────────────────────────────────────

    def compute_grasp_pose(self, x_offset=0.0):
        """Compute the target gripper_base_link pose in the world frame.

        Args:
            x_offset: Unused here, kept for API compatibility.

        Returns:
            geometry_msgs.msg.Pose (world frame, for gripper_base_link), or
            None on TF failure.
        """
        planning_frame = self.get_parameter('planning_frame').value
        toilet_frame   = self.get_parameter('toilet_frame').value

        # Get toilet pose in world frame from live TF
        T_world_toilet = self.get_transform_matrix(planning_frame, toilet_frame)
        if T_world_toilet is None:
            return None

        # Lid grasp position relative to the toilet frame
        gx = self.get_parameter('gap_x').value + x_offset
        gy = self.get_parameter('gap_y').value
        gz = self.get_parameter('gap_z').value

        T_toilet_grasp_pos = translation_matrix([gx, gy, gz])
        T_world_grasp_pos = np.dot(T_world_toilet, T_toilet_grasp_pos)

        lx = T_world_grasp_pos[0, 3]
        ly = T_world_grasp_pos[1, 3]
        lz = T_world_grasp_pos[2, 3]

        # Finger offset (gripper_finger = gripper_base_link + offset)
        fx = self.get_parameter('finger_offset_x').value
        fy = self.get_parameter('finger_offset_y').value
        fz = self.get_parameter('finger_offset_z').value

        # Target gripper_base_link position in world frame
        target_x = lx - fx
        target_y = ly - fy
        target_z = lz - fz

        # Orientation logic: defined relative to the toilet frame
        r  = self.get_parameter('gap_roll').value
        p  = self.get_parameter('gap_pitch').value
        y  = self.get_parameter('gap_yaw').value

        # Build rotation matrix: toilet_frame → grasp orientation
        q_grasp = euler_to_quaternion(r, p, y)
        T_toilet_grasp_ori = quaternion_matrix(q_grasp)

        # Convert orientation to world frame
        T_world_grasp_ori = np.dot(T_world_toilet, T_toilet_grasp_ori)

        pose = Pose()
        pose.position.x = target_x
        pose.position.y = target_y
        pose.position.z = target_z
        q_final = matrix_to_quaternion(T_world_grasp_ori)
        pose.orientation.x = q_final[0]
        pose.orientation.y = q_final[1]
        pose.orientation.z = q_final[2]
        pose.orientation.w = q_final[3]
        return pose

    def _plan_freespace_move(self, target_pose, speed_scale, callback_type):
        """Build and send a MoveGroup.Goal for OMPL freespace planning."""
        if not self.move_group_client.wait_for_server(timeout_sec=5.0):
            self.get_logger().error("move_action server not available! Aborting.")
            self.state = 'DONE'
            return

        goal_msg = MoveGroup.Goal()
        req = MotionPlanRequest()
        req.group_name = self.get_parameter('move_group').value

        # Translate speed_scale (stretch factor) into MoveIt velocity scaling
        scaling = max(0.01, min(1.0, 1.0 / speed_scale))
        req.max_velocity_scaling_factor     = scaling
        req.max_acceleration_scaling_factor = scaling
        req.num_planning_attempts = 3
        req.allowed_planning_time = 5.0

        # Position constraint
        pc = PositionConstraint()
        pc.header.frame_id = self.get_parameter('planning_frame').value
        pc.link_name       = self.get_parameter('end_effector_frame').value
        pc.target_point_offset.x = 0.0
        pc.target_point_offset.y = 0.0
        pc.target_point_offset.z = 0.0

        sphere = SolidPrimitive()
        sphere.type       = SolidPrimitive.SPHERE
        sphere.dimensions = [0.01]   # 1 cm tolerance

        bv = BoundingVolume()
        bv.primitives.append(sphere)
        bv.primitive_poses.append(target_pose)
        pc.constraint_region = bv
        pc.weight = 1.0

        # Orientation constraint
        oc = OrientationConstraint()
        oc.header.frame_id = self.get_parameter('planning_frame').value
        oc.link_name       = self.get_parameter('end_effector_frame').value
        oc.orientation     = target_pose.orientation
        oc.absolute_x_axis_tolerance = 0.05
        oc.absolute_y_axis_tolerance = 0.05
        oc.absolute_z_axis_tolerance = 0.05
        oc.weight = 1.0

        c = Constraints()
        c.position_constraints.append(pc)
        c.orientation_constraints.append(oc)
        req.goal_constraints.append(c)

        goal_msg.request = req
        goal_msg.planning_options.plan_only = True   # plan first, execute separately

        future = self.move_group_client.send_goal_async(goal_msg)
        future.add_done_callback(
            lambda f: self._freespace_goal_response_cb(f, speed_scale, callback_type)
        )

    def _freespace_goal_response_cb(self, future, speed_scale, callback_type):
        goal_handle = future.result()
        if not goal_handle.accepted:
            self.get_logger().error(f"MoveGroup goal rejected (type: {callback_type}).")
            if callback_type == 'reachability':
                self.is_checking_reachability = False
            else:
                self.state = 'DONE'
            return
            
        goal_handle.get_result_async().add_done_callback(
            lambda f: self._freespace_result_cb(f, speed_scale, callback_type)
        )

    def _freespace_result_cb(self, future, speed_scale, callback_type):
        result = future.result().result

        if callback_type == 'reachability':
            self.is_checking_reachability = False
            if result.error_code.val == 1: # Success
                self.get_logger().info(
                    "Reachability confirmed! Stopping base and transitioning to FINAL_PLANNING."
                )
                self.cmd_vel_pub.publish(Twist()) # Stop the base immediately!
                self.state = 'FINAL_PLANNING'
            else:
                # Keep moving, another check will trigger next tick if not aborted
                pass

        elif callback_type == 'final':
            self.is_checking_reachability = False
            if result.error_code.val != 1:
                self.get_logger().warn(
                    f"Final plan failed (error code: {result.error_code.val}). "
                    "Resuming navigation to move base closer."
                )
                self.state = 'NAVIGATING_AND_CHECKING_REACH'
                return

            self.get_logger().info(
                "Final freespace plan succeeded. Executing arm approach to lid grasp pose..."
            )
            self.state = 'EXECUTING_ARM'

            if not self.execute_client.wait_for_server(timeout_sec=5.0):
                self.get_logger().error("execute_trajectory server not available!")
                self.state = 'DONE'
                return

            goal_msg = ExecuteTrajectory.Goal()
            goal_msg.trajectory = result.planned_trajectory

            future_goal = self.execute_client.send_goal_async(goal_msg)
            future_goal.add_done_callback(
                lambda f: self._arm_goal_response_cb(f)
            )

    def _arm_goal_response_cb(self, future):
        goal_handle = future.result()
        if not goal_handle.accepted:
            self.get_logger().error("ExecuteTrajectory goal rejected!")
            self.state = 'DONE'
            return
        self.current_goal_handle = goal_handle
        self.get_logger().info("Arm trajectory executing...")
        goal_handle.get_result_async().add_done_callback(self._arm_result_cb)

    def _arm_result_cb(self, future):
        result = future.result().result
        status = future.result().status
        self.current_goal_handle = None

        if status == GoalStatus.STATUS_CANCELED:
            self.get_logger().warn("Arm trajectory canceled.")
            self.state = 'DONE'
            return

        if result.error_code.val != 1:
            self.get_logger().error(
                f"Arm execution failed (error code: {result.error_code.val})."
            )
            self.state = 'DONE'
            return

        self.get_logger().info(
            "Final MoveIt execution complete: gripper is at the lid "
            "grasp point. Transitioning to GRIPPING."
        )
        self.state = 'GRIPPING'
        self.handle_gripping()

    # ─────────────────────────────────────────────────────────────────────────
    # GRIPPING — position/close gripper on the lid edge
    # ─────────────────────────────────────────────────────────────────────────

    def handle_gripping(self):
        """Position the gripper fingers on the lid edge.

        This is a placeholder.  If your xArm7 has an active parallel-jaw
        gripper, publish the close command to its controller here (e.g., via
        a topic or action) and add a done-callback that transitions the state
        to 'OPENING_LID'.

        For the blade/spatula configuration, no active actuation is needed;
        the arm has already stopped at the grasp pose, so we proceed directly
        to the arc opening.
        """
        self.get_logger().info(
            "GRIPPING: Gripper is in position on the lid edge. "
            "(Extend this method to close active gripper fingers if required.) "
            "Proceeding to OPENING_LID."
        )
        self.state = 'OPENING_LID'
        self.start_lid_opening()

    # ─────────────────────────────────────────────────────────────────────────
    # OPENING_LID — arc-waypoint Cartesian trajectory
    # ─────────────────────────────────────────────────────────────────────────

    def start_lid_opening(self):
        """Generate arc waypoints from the CURRENT gripper pose and send them
        to compute_cartesian_path.  This is equivalent to the original
        plan_opening() logic, but now triggered by the state machine instead
        of a one-shot timer."""

        if not self.compute_path_client.wait_for_service(timeout_sec=2.0):
            self.get_logger().error("compute_cartesian_path not available! Aborting.")
            self.state = 'DONE'
            return

        waypoints = self.generate_waypoints()
        if not waypoints:
            self.get_logger().error("Failed to generate arc waypoints. Aborting.")
            self.state = 'DONE'
            return

        self.get_logger().info(
            f"Generated {len(waypoints)} arc waypoints. "
            "Sending to compute_cartesian_path..."
        )

        req = GetCartesianPath.Request()
        req.header.frame_id = self.get_parameter('planning_frame').value
        req.group_name      = self.get_parameter('move_group').value
        req.waypoints       = waypoints
        req.max_step        = 0.01
        req.jump_threshold  = 0.0
        # Collision checking is disabled: MoveIt sees the lid as static/closed.
        # Gazebo physics handles the actual contact force during the sweep.
        req.avoid_collisions = False

        self.last_goal_pose = waypoints[-1]

        future = self.compute_path_client.call_async(req)
        future.add_done_callback(self._arc_path_computed_cb)

    def generate_waypoints(self):
        """Generate the arc of end-effector waypoints that sweep the lid open.

        The arc is anchored to the hinge TF and the CURRENT gripper position
        so that the trajectory is correct regardless of where the robot stopped.

        Returns:
            List[Pose] in the planning frame, or None on failure.
        """
        planning_frame  = self.get_parameter('planning_frame').value
        toilet_frame    = self.get_parameter('toilet_frame').value
        ee_frame        = self.get_parameter('end_effector_frame').value

        T_world_toilet  = self.get_transform_matrix(planning_frame, toilet_frame)
        if T_world_toilet is None:
            return None

        # Hinge transform in world frame (from URDF constants)
        q_hinge      = euler_to_quaternion(*self.hinge_origin_rpy)
        T_toilet_hinge = np.dot(translation_matrix(self.hinge_origin_xyz),
                                quaternion_matrix(q_hinge))
        T_world_hinge = np.dot(T_world_toilet, T_toilet_hinge)

        # Current gripper pose in world frame
        T_world_gripper = self.get_transform_matrix(planning_frame, ee_frame)
        if T_world_gripper is None:
            self.get_logger().error(f"Could not get TF for {ee_frame}.")
            return None

        # Relative pose of gripper w.r.t. hinge at theta=0 (grasp position)
        T_hinge_gripper_initial = np.dot(np.linalg.inv(T_world_hinge), T_world_gripper)

        theta_start   = self.get_parameter('theta_start').value
        theta_end     = self.get_parameter('theta_end').value
        num_waypoints = self.get_parameter('num_waypoints').value
        tilt_fraction = self.get_parameter('tilt_fraction').value

        thetas    = np.linspace(theta_start, theta_end, num_waypoints)
        waypoints = []

        for theta in thetas:
            # Position follows full rotation (traces the lid edge arc)
            q_rot_pos     = euler_to_quaternion(0, 0, theta)
            T_hinge_rot_pos = quaternion_matrix(q_rot_pos)

            # Orientation only tilts a fraction → avoids wrist joint limits
            q_rot_ori     = euler_to_quaternion(0, 0, theta * tilt_fraction)
            T_hinge_rot_ori = quaternion_matrix(q_rot_ori)

            T_world_pos = np.dot(T_world_hinge,
                                 np.dot(T_hinge_rot_pos, T_hinge_gripper_initial))
            T_world_ori = np.dot(T_world_hinge,
                                 np.dot(T_hinge_rot_ori, T_hinge_gripper_initial))

            pose = Pose()
            pose.position.x = T_world_pos[0, 3]
            pose.position.y = T_world_pos[1, 3]
            pose.position.z = T_world_pos[2, 3]

            q_final = matrix_to_quaternion(T_world_ori)
            pose.orientation.x = q_final[0]
            pose.orientation.y = q_final[1]
            pose.orientation.z = q_final[2]
            pose.orientation.w = q_final[3]
            waypoints.append(pose)

        # Publish arc for RViz visualisation
        pose_array = PoseArray()
        pose_array.header.frame_id = planning_frame
        pose_array.header.stamp    = self.get_clock().now().to_msg()
        pose_array.poses           = waypoints
        self.waypoint_pub.publish(pose_array)

        return waypoints

    def _arc_path_computed_cb(self, future):
        """Callback after compute_cartesian_path returns for the lid-open arc."""
        try:
            response = future.result()
        except Exception as e:
            self.get_logger().error(f"compute_cartesian_path call failed: {e}")
            self.state = 'DONE'
            return

        self.get_logger().info(
            f"Cartesian arc computed. Fraction achieved: {response.fraction:.4f}"
        )

        if response.fraction < 0.05:
            self.get_logger().error("Arc path planning failed (fraction < 5%). Aborting.")
            self.state = 'DONE'
            return

        if response.fraction < 0.9:
            self.get_logger().warn(
                f"Arc is incomplete ({response.fraction * 100:.1f}%). "
                "Executing partial path — watch the robot carefully!"
            )
        else:
            self.get_logger().info(
                f"Full arc planned ({response.fraction * 100:.1f}%). Executing..."
            )

        # Scale down trajectory speed (higher speed_scale → slower motion)
        speed_scale = self.get_parameter('speed_scale').value
        for pt in response.solution.joint_trajectory.points:
            total_time = pt.time_from_start.sec + pt.time_from_start.nanosec * 1e-9
            total_time *= speed_scale
            pt.time_from_start.sec    = int(total_time)
            pt.time_from_start.nanosec = int((total_time - int(total_time)) * 1e9)
            pt.velocities    = [v / speed_scale for v in pt.velocities]
            pt.accelerations = [a / (speed_scale ** 2) for a in pt.accelerations]

        # Log the final goal pose for diagnostics
        if hasattr(self, 'last_goal_pose'):
            gp = self.last_goal_pose
            self.get_logger().info(
                f"Arc target → pos=({gp.position.x:.3f}, {gp.position.y:.3f}, "
                f"{gp.position.z:.3f}) | ori=({gp.orientation.x:.3f}, "
                f"{gp.orientation.y:.3f}, {gp.orientation.z:.3f}, "
                f"{gp.orientation.w:.3f})"
            )

        if not self.execute_client.wait_for_server(timeout_sec=5.0):
            self.get_logger().error("ExecuteTrajectory server not available!")
            self.state = 'DONE'
            return

        goal_msg = ExecuteTrajectory.Goal()
        goal_msg.trajectory = response.solution

        self.execute_client.send_goal_async(goal_msg).add_done_callback(
            self._arc_goal_response_cb
        )

    def _arc_goal_response_cb(self, future):
        goal_handle = future.result()
        if not goal_handle.accepted:
            self.get_logger().error("Arc execution goal rejected!")
            self.state = 'DONE'
            return
        self.current_goal_handle = goal_handle
        self.get_logger().info("Arc trajectory accepted — lid opening in progress...")
        goal_handle.get_result_async().add_done_callback(self._arc_result_cb)

    def _arc_result_cb(self, future):
        result = future.result().result
        status = future.result().status
        self.current_goal_handle = None

        if status == GoalStatus.STATUS_CANCELED:
            self.get_logger().warn("Arc trajectory canceled.")
        elif result.error_code.val == 1:
            self.get_logger().info("Lid opened successfully!")
        else:
            self.get_logger().error(
                f"Arc execution failed (error code: {result.error_code.val})."
            )
        self.state = 'DONE'


